from collections import namedtuple

def t(f):
    try:
        r = f()
        print(type(r).__name__, r)
    except Exception as e:
        print(type(e).__name__)

Point = namedtuple('Point', ['x', 'y'])
p = Point(1, 2)
print(p, repr(p), str(p), p.x, p.y, p[0], p[1], p[-1], len(p))
print(Point(x=3, y=4), Point(5, y=6), Point(y=8, x=7))
x, y = p
print(x, y, list(p), tuple(p), [*p], dict(zip('ab', p)))
print(p == (1, 2), (1, 2) == p, p == Point(1, 2), p != Point(1, 3), p < Point(1, 3), p > (0, 9), sorted([Point(2, 1), Point(1, 5), Point(1, 2)]))
print(hash(p) == hash((1, 2)), {p: 'a'}[(1, 2)], {(1, 2): 'b'}[p], p in {Point(1, 2)}, p in [(1, 2)], 2 in p, 3 in p)
print(p.count(1), p.index(2), p[0:1], p[::-1], type(p[0:1]).__name__, p + (3,), p * 2)
print(type(p).__name__, type(p) is Point, isinstance(p, Point), isinstance(p, tuple), isinstance((1, 2), Point), issubclass(Point, tuple), issubclass(tuple, Point), Point)
print(Point.__name__, Point._fields, p._fields, Point._field_defaults)
print(p._asdict(), p._replace(x=10), p._replace(), Point._make([7, 8]), Point._make((9, 10)), p)
print(max(p), min(p), sum(p), any(p), all(p), list(map(str, p)), list(enumerate(p)))
print(len(Point(1, 2)), bool(Point(0, 0)), Point(0, 0) == (0, 0))
print(Point(1, [2]), Point('a', None), Point(Point(1, 2), 3), (Point(1, 2),))

