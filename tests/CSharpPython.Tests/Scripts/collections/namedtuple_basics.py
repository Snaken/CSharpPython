# Several types do not mix.
Other = namedtuple('Point', ['x', 'y'])
print(Other(1, 2) == p, isinstance(p, Other), type(p) is Other, Other is Point)

# defaults
D = namedtuple('D', 'a b c', defaults=[10, 20])
print(D(1), D(1, 2), D(1, 2, 3), D(a=0, c=5), D._field_defaults)
E2 = namedtuple('E2', 'a b', defaults=(5,))
print(E2(1), E2._field_defaults)
print(namedtuple('F', 'a b', defaults=None)(1, 2))
print(namedtuple('G', 'a', defaults=[1])())

