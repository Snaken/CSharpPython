def t(f):
    try:
        r = f()
        print(type(r).__name__, repr(r))
    except Exception as e:
        print(type(e).__name__)
t(lambda: str.upper('abc'))
t(lambda: str.lower('ABC'))
t(lambda: list(map(str.upper, ['a', 'b'])))
t(lambda: sorted(['b', 'A', 'c'], key=str.lower))
