def t(f, a):
    try:
        print(f % a)
    except Exception as e:
        print(type(e).__name__, e)
t('%d %d', (1,))
t('%d', (1, 2))
t('%d', 'x')
t('%d', None)
t('%x', 1.5)
t('%f', 'x')
t('%c', 'ab')
t('%c', 1.5)
t('%c', -1)
t('%z', 1)
t('%', ())
t('%(a)s', 5)
t('%(a)s', {})
t('%(a', {})
t('%s', ())
t('%*d', ('a', 1))
t('%*d', (1,))
t('%d', float('inf'))
t('%d', float('nan'))
t('%', 5)
t('%s %s', {'a': 1})
t('%s', {'a': 1, 'b': 2})
